import type { Exercise, ExerciseTranslation } from '../types'
import { blankMarker } from '../services/exercise-translation'
import { normalizeWord } from '../services/dictionary'

type TextRow = [source: string, russian: string, words?: string]

function translation(rows: TextRow[]): ExerciseTranslation {
  return {
    texts: Object.fromEntries(rows.map(([source, russian]) => [source, russian])),
    contextual: Object.fromEntries(rows.flatMap(([source, , words]) => words ? [[source, Object.fromEntries(
      words.split(';').map(pair => {
        const [word, russian] = pair.split('=')
        return [normalizeWord(word), russian]
      }),
    )]] : [])),
  }
}

